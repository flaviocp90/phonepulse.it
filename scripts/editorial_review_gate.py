"""Human editorial review ledger -> grounded, review-only brief.

The ledger is an explicit human input, never generated by the retrieval or LLM
pipeline. This is a local audit contract, NOT identity authentication: the admin
must later bind the reviewer to a verified session and persist the record.
"""
from __future__ import annotations

import argparse
from datetime import datetime
import hashlib
import json
from pathlib import Path
import re

from editorial_evidence import Claim, Source, canonical_public_url
from editorial_review_brief import build_reviewed_brief


class ReviewError(ValueError):
    pass


def manifest_fingerprint(manifest: dict) -> str:
    """Hash the substantive evidence, excluding non-semantic timestamps."""
    stable = {key: manifest.get(key) for key in
              ("schema_version", "topic", "sources", "candidate_evidence", "assessment")}
    serialized = json.dumps(stable, ensure_ascii=False, sort_keys=True, separators=(",", ":"))
    return hashlib.sha256(serialized.encode("utf-8")).hexdigest()


def _parse_time(value: object) -> str:
    if not isinstance(value, str):
        raise ReviewError("A review timestamp with timezone is required")
    try:
        dt = datetime.fromisoformat(value.replace("Z", "+00:00"))
    except ValueError as exc:
        raise ReviewError("Invalid review timestamp") from exc
    if dt.tzinfo is None or dt.utcoffset() is None:
        raise ReviewError("Review timestamp must include timezone")
    return value


def compile_reviewed_brief(manifest: dict, ledger: dict) -> dict:
    """Require an explicit review of every claim with bound source evidence.

    This validates the consistency of the review record, NOT the semantic truth
    of each assertion. The final article still needs independent approval.
    """
    if manifest.get("schema_version") != 1 or manifest.get("mode") != "live_readonly":
        raise ReviewError("A live-readonly evidence manifest is required")
    if manifest.get("publication_allowed") is not False:
        raise ReviewError("Unexpected publication status")
    if ledger.get("manifest_sha256") != manifest_fingerprint(manifest):
        raise ReviewError("Review refers to different evidence version")
    reviewer = ledger.get("reviewer_id")
    if not isinstance(reviewer, str) or not re.fullmatch(r"[a-zA-Z0-9_.@-]{3,100}", reviewer):
        raise ReviewError("Named reviewer ID required")
    reviewed_at = _parse_time(ledger.get("reviewed_at"))
    source_map = {}
    for row in manifest.get("sources", []):
        sid = row.get("source_id")
        if not sid or sid in source_map:
            raise ReviewError("Duplicate/missing source ID")
        source_map[sid] = row
    candidates = {}
    for item in manifest.get("candidate_evidence", []):
        cid = item.get("candidate_id")
        if not cid or cid in candidates:
            raise ReviewError("Duplicate/missing candidate ID")
        sid = item.get("source_id")
        source = source_map.get(sid)
        if not source or source.get("retrieval") != "ok":
            raise ReviewError("Evidence from unavailable source")
        if item.get("source_url") != source.get("final_url"):
            raise ReviewError("Evidence URL differs from retrieved final URL")
        if item.get("verification") != "unverified":
            raise ReviewError("Candidate was not unverified")
        if not isinstance(item.get("sentence_sha256"), str) or not re.fullmatch(
                r"[a-f0-9]{64}", item["sentence_sha256"]):
            raise ReviewError("Missing candidate text digest")
        candidates[cid] = item

    claim_rows = manifest.get("assessment", {}).get("claims", [])
    if not claim_rows or not isinstance(claim_rows, list):
        raise ReviewError("No claims to review")
    decisions = ledger.get("decisions")
    if not isinstance(decisions, list) or len(decisions) != len(claim_rows):
        raise ReviewError("Each claim requires one explicit decision")
    review_by_id = {}
    for decision in decisions:
        cid = decision.get("claim_id")
        if not cid or cid in review_by_id:
            raise ReviewError("Duplicate or missing reviewed claim ID")
        if decision.get("decision") not in ("approve", "reject", "needs_research"):
            raise ReviewError("Invalid review decision")
        review_by_id[cid] = decision
    if set(review_by_id) != {item.get("claim_id") for item in claim_rows}:
        raise ReviewError("Review decisions do not cover the source claims")

    sources = [Source(
        source_id=sid, url=canonical_public_url(row["url"]),
        publisher=row["publisher"], kind=row["kind"],
        fetched=row["retrieval"] == "ok"
    ) for sid, row in source_map.items()]

    claims = []
    audit = []
    for claim in claim_rows:
        cid = claim["claim_id"]
        decision = review_by_id[cid]
        approved = decision["decision"] == "approve"
        evidence_ids = decision.get("candidate_ids", [])
        if not isinstance(evidence_ids, list) or len(evidence_ids) != len(set(evidence_ids)):
            raise ReviewError("Invalid or duplicated evidence IDs")
        refs = set(claim.get("supporting_sources", []))
        if approved:
            if claim.get("status") == "conflicted" or claim.get("conflicting_sources"):
                raise ReviewError("Conflicted claim cannot be approved")
            if not evidence_ids:
                raise ReviewError("Approved claim requires inspected source evidence")
            if not isinstance(decision.get("rationale"), str) or len(
                    decision["rationale"].strip()) < 20:
                raise ReviewError("Approval needs an explicit editorial rationale")
            for eid in evidence_ids:
                candidate = candidates.get(eid)
                if not candidate or candidate["source_id"] not in refs:
                    raise ReviewError("Evidence not connected to claim supporting source")
        claims.append(Claim(
            claim_id=cid, statement=claim["statement"],
            supporting_source_ids=tuple(refs),
            conflicting_source_ids=tuple(claim.get("conflicting_sources", [])),
            editorially_verified=approved,
        ))
        audit.append({
            "claim_id": cid, "decision": decision["decision"],
            "candidate_ids": evidence_ids, "rationale": str(decision.get("rationale", ""))[:500]
        })

    if any(item["decision"] != "approve" for item in audit):
        raise ReviewError("Unapproved claims must be researched or excluded in a new manifest")

    brief = build_reviewed_brief(sources, claims)
    brief["review"] = {
        "reviewer_id": reviewer, "reviewed_at": reviewed_at,
        "manifest_sha256": manifest_fingerprint(manifest), "decisions": audit,
        "authentication_verified": False,
    }
    brief["publish_allowed"] = False
    return brief


def main(argv=None):
    parser = argparse.ArgumentParser(description="PhonePulse offline editorial review gate")
    parser.add_argument("--manifest", required=True, type=Path)
    parser.add_argument("--review", required=True, type=Path)
    parser.add_argument("--output", required=True, type=Path)
    args = parser.parse_args(argv)
    manifest = json.loads(args.manifest.read_text(encoding="utf-8"))
    ledger = json.loads(args.review.read_text(encoding="utf-8"))
    brief = compile_reviewed_brief(manifest, ledger)
    args.output.write_text(json.dumps(brief, ensure_ascii=False, indent=2) + "\n",
                           encoding="utf-8")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
